"""Exact installed artifact identities using small inert distribution fixtures."""

import importlib.machinery
import importlib.metadata
import shutil
import sys
from pathlib import Path

import pytest

from frem_s10.errors import IntegrityError
from frem_s10.runtime.smoke_contract import _hash_regular, _interpreter_identity, numpy_artifact_identity


def distribution_tree(path: Path) -> importlib.metadata.PathDistribution:
    paths = {
        "numpy/__init__.py": b"fixture Python source\n",
        "numpy/_core/_multiarray_umath.fixture.so": b"fixture native artifact",
        "numpy.libs/libopenblas-fixture.so.0": b"fixture bundled library",
    }
    for name, payload in paths.items():
        member = path / name
        member.parent.mkdir(parents=True, exist_ok=True)
        member.write_bytes(payload)
    info = path / "numpy-2.5.4.dist-info"
    info.mkdir()
    (info / "METADATA").write_text("Name: numpy\nVersion: 2.5.4\n")
    (info / "RECORD").write_text("".join(f"{name},,\n" for name in paths))
    return importlib.metadata.PathDistribution(info)


def select(distribution: importlib.metadata.PathDistribution, monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(
        "frem_s10.runtime.smoke_contract.importlib.metadata.distribution", lambda name: distribution
    )
    origin = str(distribution.locate_file("numpy/__init__.py"))
    monkeypatch.setattr(
        "frem_s10.runtime.smoke_contract.importlib.util.find_spec",
        lambda name: importlib.machinery.ModuleSpec(name, None, origin=origin),
    )


def test_same_version_native_and_bundled_library_changes_change_identity(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    distribution = distribution_tree(tmp_path)
    select(distribution, monkeypatch)
    first = numpy_artifact_identity()
    assert first["version"] == "2.5.4"
    assert first["files"] == 3
    native = tmp_path / "numpy/_core/_multiarray_umath.fixture.so"
    native.write_bytes(native.read_bytes() + b"different build")
    second = numpy_artifact_identity()
    assert first["manifest_sha256"] != second["manifest_sha256"]
    library = tmp_path / "numpy.libs/libopenblas-fixture.so.0"
    library.write_bytes(library.read_bytes() + b"different backend")
    assert second["manifest_sha256"] != numpy_artifact_identity()["manifest_sha256"]


def test_identity_is_relocatable_and_ignores_generated_bytecode(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    original = tmp_path / "original"
    distribution = distribution_tree(original)
    select(distribution, monkeypatch)
    first = numpy_artifact_identity()
    target = tmp_path / "relocated"
    shutil.copytree(original, target)
    cache = target / "numpy/__pycache__"
    cache.mkdir()
    (cache / "__init__.cpython-312.pyc").write_bytes(b"generated bytecode")
    select(importlib.metadata.PathDistribution(target / "numpy-2.5.4.dist-info"), monkeypatch)
    assert numpy_artifact_identity() == first
    assert str(tmp_path) not in str(first)


@pytest.mark.parametrize(
    "defect", ("missing_record", "omitted_file", "missing_file", "duplicate", "symlink", "shadow")
)
def test_incomplete_or_unsafe_installation_fails_closed(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, defect: str
) -> None:
    distribution = distribution_tree(tmp_path)
    select(distribution, monkeypatch)
    record = tmp_path / "numpy-2.5.4.dist-info/RECORD"
    native = tmp_path / "numpy/_core/_multiarray_umath.fixture.so"
    if defect == "missing_record":
        record.unlink()
    elif defect == "omitted_file":
        (tmp_path / "numpy/extra.py").write_text("unregistered source")
    elif defect == "missing_file":
        native.unlink()
    elif defect == "duplicate":
        record.write_text(record.read_text() + "numpy/__init__.py,,\n")
    elif defect == "symlink":
        native.unlink()
        native.symlink_to(tmp_path / "numpy/__init__.py")
    else:
        monkeypatch.setattr(
            "frem_s10.runtime.smoke_contract.importlib.util.find_spec",
            lambda name: importlib.machinery.ModuleSpec(name, None, origin=str(tmp_path / "shadow/numpy.py")),
        )
    with pytest.raises(IntegrityError):
        numpy_artifact_identity()


def test_actual_byte_bound_and_missing_native_core_fail(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    distribution = distribution_tree(tmp_path)
    select(distribution, monkeypatch)
    with pytest.raises(IntegrityError, match=r"bounded|bound"):
        numpy_artifact_identity(maximum_bytes=8)
    record = tmp_path / "numpy-2.5.4.dist-info/RECORD"
    record.write_text("numpy/__init__.py,,\n")
    with pytest.raises(IntegrityError, match="native core"):
        numpy_artifact_identity()


def test_streamed_hash_and_interpreter_identity_without_numerical_import(tmp_path: Path) -> None:
    file = tmp_path / "binary"
    file.write_bytes(b"bounded bytes")
    digest, size = _hash_regular(file, 100)
    assert len(digest) == 64 and size == 13
    with pytest.raises(IntegrityError):
        _hash_regular(file, 4)
    before = "numpy" in sys.modules
    interpreter = _interpreter_identity()
    assert len(str(interpreter["sha256"])) == 64
    assert interpreter["bytes"]
    assert interpreter["soabi"]
    assert ("numpy" in sys.modules) is before
    assert sys.executable not in str(interpreter)
