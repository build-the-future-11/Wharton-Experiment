from datetime import datetime, timedelta, timezone
from pathlib import Path
import csv, hashlib, json
import numpy as np

def write_generated_panel(directory):
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=False)
    rng = np.random.Generator(np.random.PCG64(431))
    shocks = rng.standard_normal((660, 4))
    loadings = np.array([1.0, -0.5], dtype=np.float64)
    latent = 0.0
    returns = np.empty((660, 2), dtype=np.float64)
    for t in range(660):
        regime = 1.0 if (t // 160) % 2 == 0 else -1.0
        log_growth = (0.0005 * regime + 0.003 * latent) * loadings
        log_growth = log_growth + 0.004 * shocks[t, 1] + 0.006 * shocks[t, 2:4]
        returns[t] = np.expm1(log_growth)
        latent = 0.85 * latent + np.sqrt(1.0 - 0.85**2) * shocks[t, 0]
    start = datetime(2020, 1, 1, tzinfo=timezone.utc)
    csv_path = directory / "synthetic_component_panel.csv"
    with csv_path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerow(["decision_time", "observed_at", "SYNTH_A", "SYNTH_B"])
        for t, row in enumerate(returns):
            decision = start + timedelta(days=t)
            observed = decision + timedelta(hours=1)
            writer.writerow([decision.isoformat(), observed.isoformat(), *[format(float(v), ".17g") for v in row]])
    checksum = hashlib.sha256(csv_path.read_bytes()).hexdigest()
    manifest = {
        "csv": csv_path.name, "sha256": checksum,
        "assets": ["SYNTH_A", "SYNTH_B"],
        "source": "WHARTON-A20261008-R2-SYNTH-CV-001; explicitly generated synthetic component data",
        "license": "Generated by this protocol from NumPy PCG64 draws; no market data imported",
        "lawful_use_attested": True, "asset_order_verified": True,
        "role": "development", "data_kind": "synthetic_fixture",
        "return_kind": "total", "protected_rows": []
    }
    manifest_path = directory / "manifest.json"
    manifest_path.write_text(json.dumps(manifest, sort_keys=True, indent=2) + "\n", encoding="utf-8")
    return manifest_path
